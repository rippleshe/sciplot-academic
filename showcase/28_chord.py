"""
28_chord.py — 弦图

展示 plot_chord()：八大港口城市间的集装箱货流（万 TEU/年）。
按区域分组着色（华北/华东/华南/西南），min_flow 过滤低频航线。
"""

import numpy as np
import sciplot as sp

# ── 数据生成 ──────────────────────────────────────────────────
cities = ["大连", "天津", "青岛", "上海", "宁波", "广州", "深圳", "成都"]
regions = ["华北", "华北", "华北", "华东", "华东", "华南", "华南", "西南"]

# 非对称流量矩阵：行=出发港，列=到达港（万 TEU/年）
# 结构：沿海枢纽（上海/深圳）为核心，区域间干线强、支线弱
flow = np.array([
    # 大连  天津  青岛  上海  宁波  广州  深圳  成都
    [  0,    4,    3,   12,    2,    1,    1,    0],   # 大连
    [  5,    0,    6,   10,    1,    1,    0,    0],   # 天津
    [  3,    5,    0,   14,    3,    2,    1,    0],   # 青岛
    [ 11,    9,   13,    0,   18,    8,   10,    2],   # 上海
    [  2,    1,    3,   16,    0,    4,    3,    0],   # 宁波
    [  1,    1,    2,    9,    3,    0,   12,    1],   # 广州
    [  1,    0,    1,   11,    2,   11,    0,    1],   # 深圳
    [  0,    0,    0,    2,    0,    1,    1,    0],   # 成都
], dtype=float)

# ── 绘图 ──────────────────────────────────────────────────────
sp.setup_style("presentation", "ocean", lang="zh")

fig, ax = sp.plot_chord(
    flow,
    labels=cities,
    color_by=regions,
    min_flow=2.0,        # 过滤低频支线（<2 万 TEU 不画）
    show_values=True,
)

# ── 保存 ──────────────────────────────────────────────────────
sp.save(fig, "showcase/28_chord", formats=("png",), dpi=300)
