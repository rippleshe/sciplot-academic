"""
31_sankey.py — 桑基图

展示 plot_sankey()：某区域能源系统的能源流向（PWh/年）。
三层结构：一次能源 → 转化环节 → 终端消费，节点高度与流量带宽度
均正比于流量值。
"""

import sciplot as sp

# ── 数据 ──────────────────────────────────────────────────────
# 源节点 → 目标节点 → 流量（PWh/年）
sources = [
    "煤炭", "煤炭", "石油", "石油", "天然气", "天然气", "水电", "核电",
    "太阳能", "风电", "生物质", "生物质",
]
targets = [
    "电力转化", "工业直接", "交通", "化工原料", "电力转化", "供暖",
    "电力转化", "电力转化", "电力转化", "电力转化", "电力转化", "农业",
]
values = [
    35.0, 18.0, 12.0, 8.0, 10.0, 6.0,
    4.5, 3.2, 2.8, 3.5, 1.5, 1.2,
]
extra_sources = ["电力转化", "电力转化", "电力转化", "电力转化"]
extra_targets = ["工业用电", "居民用电", "商业用电", "交通"]
extra_values = [22.0, 14.0, 9.0, 4.5]

# ── 绘图 ──────────────────────────────────────────────────────
sp.setup_style("presentation", "pastel", lang="zh")

fig, ax = sp.plot_sankey(
    sources + extra_sources,
    targets + extra_targets,
    values + extra_values,
    node_colors=[
        "#5B7DB1", "#5B7DB1", "#8C6D5F", "#8C6D5F", "#7FB3A6", "#7FB3A6",
        "#3E7CB1", "#D9A23C", "#E07B54", "#6BBF8A", "#9B8EC4", "#9B8EC4",
        "#E07B54", "#E07B54", "#E07B54", "#E07B54", "#A8B8C8",
    ],
    min_flow=1.0,
)

# ── 保存 ──────────────────────────────────────────────────────
sp.save(fig, "showcase/31_sankey", formats=("png",), dpi=300)
