"""
22_gantt.py — 甘特图

展示 plot_gantt()：科研项目 10 周执行计划。
包含：三阶段背景色带、里程碑（中期检查/结题验收）、
任务依赖箭头、当前时间线。
"""

import numpy as np
import sciplot as sp

# ── 数据生成 ──────────────────────────────────────────────────
tasks = [
    "文献调研", "实验设计", "数据采集", "数据清洗", "模型开发",
    "实验验证", "结果分析", "论文撰写", "同行评审修改", "投稿准备",
]
start = [0.0, 0.5, 2.0, 4.5, 5.5, 7.0, 8.0, 8.5, 9.2, 9.6]
duration = [1.5, 1.5, 2.5, 1.0, 1.5, 1.0, 0.8, 0.7, 0.4, 0.4]
phases = ["前期", "前期", "中期", "中期", "中期", "中期", "后期", "后期", "后期", "后期"]

milestones = {
    "中期检查": 4.0,
    "结题验收": 9.9,
}
dependencies = [
    (0, 1),   # 文献调研 → 实验设计
    (1, 2),   # 实验设计 → 数据采集
    (2, 3),   # 数据采集 → 数据清洗
    (3, 4),   # 数据清洗 → 模型开发
    (4, 5),   # 模型开发 → 实验验证
    (5, 6),   # 实验验证 → 结果分析
    (6, 7),   # 结果分析 → 论文撰写
    (7, 8),   # 论文撰写 → 评审修改
    (8, 9),   # 评审修改 → 投稿准备
]
now = 5.2

# ── 绘图 ──────────────────────────────────────────────────────
sp.setup_style("thesis", "pastel", lang="zh")

fig, ax = sp.plot_gantt(
    tasks,
    start=start,
    duration=duration,
    color_by=phases,
    groups=phases,
    milestones=milestones,
    dependencies=dependencies,
    now=now,
    xlabel="周次",
    ylabel="任务",
)

# ── 保存 ──────────────────────────────────────────────────────
sp.save(fig, "showcase/22_gantt", formats=("png",), dpi=300)
